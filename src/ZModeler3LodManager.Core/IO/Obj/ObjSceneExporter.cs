using ZModeler3LodManager.Core.Models;

namespace ZModeler3LodManager.Core.IO.Obj;

/// <summary>
/// Exports a Scene back to Wavefront .obj. The vertex pool is written back verbatim, and every
/// leaf node (including duplicated LOD copies) is written as its own "o" block reusing the same
/// shared vertex indices - duplicating a part only duplicates its face-list lines, never any
/// vertex data, so the result is always valid OBJ and the original geometry is never altered.
/// </summary>
public static class ObjSceneExporter
{
    public static void Export(Scene scene, string filePath)
    {
        using var writer = new StreamWriter(filePath);

        if (scene.ObjHeaderLines is { Count: > 0 })
        {
            foreach (var line in scene.ObjHeaderLines)
            {
                writer.WriteLine(line);
            }
        }
        else
        {
            writer.WriteLine("# Generated by ZModeler3 LOD Manager");
        }

        foreach (var root in scene.Roots)
        {
            foreach (var leaf in root.DescendantsAndSelf().Where(n => n.Children.Count == 0))
            {
                writer.WriteLine($"o {leaf.Path}");
                if (leaf.RawGeometryLines is null)
                {
                    continue;
                }

                foreach (var line in leaf.RawGeometryLines)
                {
                    writer.WriteLine(line);
                }
            }
        }
    }
}
